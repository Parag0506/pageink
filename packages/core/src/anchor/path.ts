/**
 * Structural addresses for elements. Three locators with different weak spots:
 * the id, a CSS path from the nearest stable id, and an absolute positional path.
 * Shadow trees are crossed with " >>> " between the host's path and the inner path.
 */
import type { AnchorContext, ElementPath } from '../types';
import { shadowOf } from './text';

export const SHADOW_SEP = ' >>> ';

const SIMPLE_ID = /^[A-Za-z][\w-]{0,79}$/;
const GENERATED_PREFIX =
  /^(ember|yui|ext-|mui-|radix-|headlessui-|react-|rc-|uid|gwt|j_id|ng-|vue-|svelte-|jsx-|css-|sc-|tippy-|popover-|dropdown-|tooltip-|downshift-|mat-|cdk-|el-|ui-id-|id-|_)/i;

/** True for ids that look written by a person, not generated by a framework or a build. */
export function isStableId(id: string): boolean {
  if (!SIMPLE_ID.test(id)) return false;
  if (/\d{3,}/.test(id)) return false;
  const digits = id.replace(/\D/g, '').length;
  if (digits / id.length > 0.25) return false;
  if (GENERATED_PREFIX.test(id) && digits > 0) return false;
  // Hash-like chunks mix letters and digits, or are long runs of hex.
  for (const part of id.split(/[-_]/)) {
    if (part.length >= 5 && /\d/.test(part) && /[a-z]/i.test(part)) return false;
    if (part.length >= 8 && /^[0-9a-f]+$/i.test(part) && /\d/.test(part)) return false;
  }
  return true;
}

function nthOfType(el: Element): number {
  let n = 1;
  for (let s = el.previousElementSibling; s; s = s.previousElementSibling)
    if (s.localName === el.localName) n++;
  return n;
}

/** Steps from the top of el's tree down to el. */
function chain(el: Element): Element[] {
  const out: Element[] = [];
  for (let e: Element | null = el; e; e = e.parentElement) out.push(e);
  return out.reverse();
}

const tagOk = (t: string) => /^[a-z][a-z0-9-]*$/.test(t);

function cssIn(el: Element, inDocument: boolean): string {
  const steps: string[] = [];
  for (let e: Element | null = el; e; e = e.parentElement) {
    if (e.id && isStableId(e.id) && (e.getRootNode() as Document | ShadowRoot).getElementById?.(e.id) === e) {
      steps.push(`#${e.id}`);
      return steps.reverse().join(' > ');
    }
    if (inDocument && (e.localName === 'body' || e.localName === 'html')) {
      steps.push(e.localName);
      return steps.reverse().join(' > ');
    }
    const t = tagOk(e.localName) ? e.localName : '*';
    steps.push(`${t}:nth-of-type(${nthOfType(e)})`);
  }
  return steps.reverse().join(' > ');
}

function xpathIn(el: Element): string {
  return chain(el)
    .map((e) => `/${e.localName}[${nthOfType(e)}]`)
    .join('');
}

/** Path for an element. Crosses shadow roots. */
export function pathOf(el: Element): ElementPath {
  const trees: Element[] = [];
  for (let e: Element | null = el; e; ) {
    trees.push(e);
    const root = e.getRootNode();
    e = root.nodeType === 11 ? (root as ShadowRoot).host : null;
  }
  trees.reverse();
  const css = trees.map((e, i) => cssIn(e, i === 0)).join(SHADOW_SEP);
  const xpath = trees.map((e) => xpathIn(e)).join(SHADOW_SEP);
  const out: ElementPath = { css, xpath };
  if (trees.length === 1 && el.id && isStableId(el.id)) out.id = el.id;
  return out;
}

type Root = Document | ShadowRoot;

function childOfType(parent: ParentNode, tag: string, n: number): Element | null {
  let k = 0;
  for (let c = parent.firstElementChild; c; c = c.nextElementSibling) {
    if (tag === '*' || c.localName === tag) {
      k++;
      if (k === n) return c;
    }
  }
  return null;
}

const CSS_STEP = /^([a-z*][a-z0-9-]*):nth-of-type\((\d+)\)$/;

function cssResolve(root: Root, sel: string): Element | null {
  const steps = sel.split(' > ');
  let cur: ParentNode | null = root;
  for (let i = 0; i < steps.length && cur; i++) {
    const s = steps[i]!;
    if (i === 0 && s.startsWith('#')) {
      cur = root.getElementById(s.slice(1));
      continue;
    }
    if (i === 0 && (s === 'body' || s === 'html') && 'body' in root) {
      cur = s === 'body' ? root.body : root.documentElement;
      continue;
    }
    const m = CSS_STEP.exec(s);
    if (!m) {
      try {
        return root.querySelector(sel);
      } catch {
        return null;
      }
    }
    cur = childOfType(cur, m[1]!, Number(m[2]));
  }
  return cur && (cur as Node).nodeType === 1 ? (cur as Element) : null;
}

const XP_STEP = /^([^[\]/]+)\[(\d+)\]$/;

function xpathResolve(root: Root, xp: string): Element | null {
  const steps = xp.split('/').filter(Boolean);
  let cur: ParentNode | null = root;
  for (const s of steps) {
    const m = XP_STEP.exec(s);
    if (!m || !cur) return null;
    cur = childOfType(cur, m[1]!, Number(m[2]));
  }
  return cur && cur !== root ? (cur as Element) : null;
}

function walkTrees(
  ctx: AnchorContext,
  parts: string[],
  one: (root: Root, s: string) => Element | null,
): Element | null {
  let root: Root | null = ctx.doc;
  let el: Element | null = null;
  for (let i = 0; i < parts.length; i++) {
    if (!root) return null;
    el = one(root, parts[i]!);
    if (!el) return null;
    if (i < parts.length - 1) root = shadowOf(ctx, el);
  }
  return el;
}

/** Elements the path points at, best locator first, without repeats. Lazy: later locators run only when asked. */
export function* resolvePath(ctx: AnchorContext, p: ElementPath): Generator<Element> {
  const seen: Element[] = [];
  const ok = (e: Element | null): e is Element => {
    if (!e || seen.includes(e) || ctx.isOurs?.(e)) return false;
    seen.push(e);
    return true;
  };
  if (p.id) {
    const e = ctx.doc.getElementById(p.id);
    if (ok(e)) yield e;
  }
  if (p.css) {
    const e = walkTrees(ctx, p.css.split(SHADOW_SEP), cssResolve);
    if (ok(e)) yield e;
  }
  if (p.xpath) {
    const e = walkTrees(ctx, p.xpath.split(SHADOW_SEP), xpathResolve);
    if (ok(e)) yield e;
  }
}
